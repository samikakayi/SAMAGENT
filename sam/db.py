"""SQLite store (``<data_dir>/sam2.sqlite3``): WAL, namespaced migrations.

One connection shared by the core loop and the UI thread, guarded by an RLock
(``check_same_thread=False``). Every query SAM makes is small (single-row
inserts, indexed reads) so calling these sync methods directly from the
asyncio loop is fine; for anything heavy use ``await db.run(fn)``.

All timestamps are REAL unix epoch seconds (UTC). JSON columns hold UTF-8
JSON text (``ensure_ascii=False``).

Packages that need their own tables do NOT edit this file: they call
``app.db.ensure_schema("<namespace>", [(1, "CREATE TABLE ..."), ...])`` in
their ``register(app)``. Versions are tracked per namespace in
``schema_versions``.
"""

