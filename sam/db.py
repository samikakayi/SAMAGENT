CORE_MIGRATIONS: list[Migration] = [(1, _CORE_V1)]


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, default=str)


def fts_match_expr(text: str, *, max_terms: int = 12) -> str | None:
    """Build a safe FTS5 MATCH expression for a trigram index.

    Trigram tokens need >= 3 characters, so shorter words are dropped; each
    term is double-quoted (no FTS syntax injection) and OR-ed. Returns None
    when nothing searchable remains (callers then fall back to LIKE).
    """
    terms: list[str] = []
    for word in normalize_ckb(text, strip_punct=True).split():
        if len(word) >= 3 and word not in terms:
            terms.append(word.replace('"', '""'))
        if len(terms) >= max_terms:
            break
    if not terms:
        return None
    return " OR ".join(f'"{t}"' for t in terms)


class Database:
    """Thread-safe SQLite wrapper. See module docstring for conventions."""

    def __init__(self, path: Path | str) -> None:
        self.path = str(path)
        if self.path != ":memory:":
            Path(self.path).parent.mkdir(parents=True, exist_ok=True)
        self._lock = threading.RLock()
        self._conn = sqlite3.connect(self.path, check_same_thread=False, isolation_level=None, timeout=10)
        self._conn.row_factory = sqlite3.Row
        with self._lock:
            if self.path != ":memory:":
                self._conn.execute("PRAGMA journal_mode=WAL")
            self._conn.execute("PRAGMA synchronous=NORMAL")
            self._conn.execute("PRAGMA foreign_keys=ON")
            self._conn.execute("PRAGMA busy_timeout=5000")
            self._conn.execute(
                "CREATE TABLE IF NOT EXISTS schema_versions (namespace TEXT PRIMARY KEY, "
                "version INTEGER NOT NULL, applied_at REAL NOT NULL)")
        self.ensure_schema("core", CORE_MIGRATIONS)

    # -- migrations --------------------------------------------------------
    def schema_version(self, namespace: str) -> int:
        row = self.query_one("SELECT version FROM schema_versions WHERE namespace=?", (namespace,))
        return int(row["version"]) if row else 0

    def ensure_schema(self, namespace: str, migrations: Sequence[Migration]) -> int:
        """Apply migrations of ``namespace`` newer than the stored version.

        Each migration is ``(version, sql_script | callable(conn))`` and runs in
        its own transaction; versions must increase. Returns the new version.
        """
        with self._lock:
            current = self.schema_version(namespace)
            for version, step in sorted(migrations, key=lambda m: m[0]):
                if version <= current:
                    continue
                self._conn.execute("BEGIN IMMEDIATE")
                try:
                    if callable(step):
                        step(self._conn)
                    else:
                        for statement in _split_sql(step):
                            self._conn.execute(statement)
                    self._conn.execute(
                        "INSERT INTO schema_versions(namespace, version, applied_at) VALUES (?,?,?) "
                        "ON CONFLICT(namespace) DO UPDATE SET version=excluded.version, applied_at=excluded.applied_at",
                        (namespace, version, time.time()))
                    self._conn.execute("COMMIT")
                except Exception:
                    self._conn.execute("ROLLBACK")
                    raise
                current = version
            return current

    # -- basic access ------------------------------------------------------
    def execute(self, sql: str, params: Sequence[Any] | dict[str, Any] = ()) -> sqlite3.Cursor:
        with self._lock:
            return self._conn.execute(sql, params)

    def executemany(self, sql: str, seq: Iterable[Sequence[Any]]) -> None:
        with self._lock, self.transaction():
            self._conn.executemany(sql, seq)

    def query(self, sql: str, params: Sequence[Any] | dict[str, Any] = ()) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(r) for r in self._conn.execute(sql, params).fetchall()]

    def query_one(self, sql: str, params: Sequence[Any] | dict[str, Any] = ()) -> dict[str, Any] | None:
        with self._lock:
            row = self._conn.execute(sql, params).fetchone()
            return dict(row) if row is not None else None

    def scalar(self, sql: str, params: Sequence[Any] | dict[str, Any] = ()) -> Any:
        with self._lock:
            row = self._conn.execute(sql, params).fetchone()
            return row[0] if row is not None else None

    def insert(self, table: str, row: dict[str, Any], *, or_ignore: bool = False) -> int:
        """Insert a dict (dict/list values are stored as JSON); return rowid."""
        if not table.replace("_", "").isalnum():
            raise ValueError("bad table name")
        cols = list(row)
        values = [(_json(v) if isinstance(v, (dict, list)) else v) for v in row.values()]
        verb = "INSERT OR IGNORE" if or_ignore else "INSERT"
        sql = f"{verb} INTO {table} ({', '.join(cols)}) VALUES ({', '.join('?' for _ in cols)})"
        with self._lock:
            return int(self._conn.execute(sql, values).lastrowid or 0)

    @contextmanager
    def transaction(self) -> Iterator[sqlite3.Connection]:
        """Explicit write transaction (re-entrant within one thread)."""
        with self._lock:
            if self._conn.in_transaction:
                yield self._conn
                return
            self._conn.execute("BEGIN IMMEDIATE")
            try:
                yield self._conn
                self._conn.execute("COMMIT")
            except BaseException:
                self._conn.execute("ROLLBACK")
                raise

    async def run(self, fn: Callable[..., Any], *args: Any) -> Any:
        """Run a heavier ``fn(db, *args)`` in a worker thread."""
        return await asyncio.to_thread(fn, self, *args)

    def close(self) -> None:
        with self._lock:
            try:
                self._conn.close()
            except sqlite3.Error:
                pass

    # -- shared helpers ------------------------------------------------------
    def log_activity(self, kind: str, name: str = "", *, ok: bool | None = None, summary: str = "",
                     detail: Any = None, duration_ms: float | None = None, source: str = "") -> int:
        """Append to the activity log. Callers must pass redacted text."""
        return self.insert("activity", {
            "at": time.time(), "kind": kind, "name": name, "ok": None if ok is None else int(ok),
            "summary": summary[:2000], "detail": None if detail is None else _json(detail)[:8000],
            "duration_ms": duration_ms, "source": source,
        })

    @staticmethod
    def quota_day(provider: str, at: float | None = None) -> str:
        """Day key for per-day counters. Gemini free quotas reset at midnight
        Pacific time; everything else is counted by the local (Iraq) day."""
        from zoneinfo import ZoneInfo
        zone = "America/Los_Angeles" if provider == "gemini" else "Asia/Baghdad"
        moment = _dt.datetime.fromtimestamp(at if at is not None else time.time(), ZoneInfo(zone))
        return moment.strftime("%Y-%m-%d")

    def bump_usage(self, provider: str, model: str, kind: str = "text", *, requests: int = 1, errors: int = 0,
                   rate_limited: int = 0, tokens_in: int = 0, tokens_out: int = 0, units: float = 0.0,
                   day: str | None = None) -> None:
        day = day or self.quota_day(provider)
        self.execute(
            "INSERT INTO usage_counters(day, provider, model, kind, requests, errors, rate_limited, tokens_in, "
            "tokens_out, units) VALUES (?,?,?,?,?,?,?,?,?,?) ON CONFLICT(day, provider, model, kind) DO UPDATE SET "
            "requests=requests+excluded.requests, errors=errors+excluded.errors, "
            "rate_limited=rate_limited+excluded.rate_limited, tokens_in=tokens_in+excluded.tokens_in, "
            "tokens_out=tokens_out+excluded.tokens_out, units=units+excluded.units",
            (day, provider, model, kind, requests, errors, rate_limited, tokens_in, tokens_out, units))

    def usage_for(self, provider: str, model: str, kind: str | None = None, day: str | None = None) -> dict[str, Any]:
        """Today's counters for provider/model (summed over kinds unless given)."""
        day = day or self.quota_day(provider)
        sql = ("SELECT COALESCE(SUM(requests),0) AS requests, COALESCE(SUM(errors),0) AS errors, "
               "COALESCE(SUM(rate_limited),0) AS rate_limited, COALESCE(SUM(tokens_in),0) AS tokens_in, "
               "COALESCE(SUM(tokens_out),0) AS tokens_out, COALESCE(SUM(units),0) AS units "
               "FROM usage_counters WHERE day=? AND provider=? AND model=?")
        params: list[Any] = [day, provider, model]
        if kind:
            sql += " AND kind=?"
            params.append(kind)
        return self.query_one(sql, params) or {}


def _split_sql(script: str) -> list[str]:
    """Split a migration script into statements (trigger bodies kept whole).

    ``sqlite3.complete_statement`` understands comments, string literals and
    BEGIN...END trigger bodies, so line accumulation is enough.
    """
    statements: list[str] = []
    buffer = ""
    for line in script.splitlines(keepends=True):
        buffer += line
        if sqlite3.complete_statement(buffer):
            if buffer.strip():
                statements.append(buffer.strip())
            buffer = ""
    if buffer.strip():
        statements.append(buffer.strip())
    return statements


